import os
import re
import tempfile
import unittest
from pathlib import Path


class SecureVersionTests(unittest.TestCase):
    # Create one database (isolated) for the security test class
    @classmethod
    def setUpClass(cls):
        # Use a temporary database so the security tests don't change local data
        cls.temp_directory = tempfile.TemporaryDirectory()
        database_path = str(Path(cls.temp_directory.name) / "test.db")
        os.environ["DATABASE_PATH"] = database_path

        import database

        database.DATABASE_PATH = database_path

        import app

        cls.app_module = app
        cls.app = app.app
        cls.app.config.update(TESTING=True)
        app.init_db()

    # Remove the temporary database after all tests finish
    @classmethod
    def tearDownClass(cls):
        cls.temp_directory.cleanup()

    # Reset database records and create a test client before each test
    def setUp(self):
        # Start each test with no users or security events from earlier tests
        connection = self.app_module.open_database()
        with connection:
            connection.execute("DELETE FROM security_events")
            connection.execute("DELETE FROM users")
        connection.close()
        self.client = self.app.test_client()

    # Extract the CSRF token needed to submit a protected form
    def csrf_token(self, response):
        # Reuse the token generated by the page for protected form requests
        match = re.search(rb'name="csrf_token" value="([^"]+)"', response.data)
        self.assertIsNotNone(match)
        return match.group(1).decode()

    # Register a user account for the test
    def register(self, email, display_name):
        # Create test accounts through the same form users would submit
        page = self.client.get("/register")
        response = self.client.post(
            "/register",
            data={
                "csrf_token": self.csrf_token(page),
                "display_name": display_name,
                "email": email,
                "password": "correct-horse-battery",
            },
        )
        self.assertEqual(response.status_code, 302)

    # Log in a registered user and establish the test session
    def login(self, email):
        # Sign in through the application so later requests have a session
        page = self.client.get("/login")
        response = self.client.post(
            "/login",
            data={
                "csrf_token": self.csrf_token(page),
                "email": email,
                "password": "correct-horse-battery",
            },
        )
        self.assertEqual(response.status_code, 302)

    # Give a registered account administrator permissions for protected tests
    def make_admin(self, email):
        # Promote a test account using the application's administrator command
        result = self.app.test_cli_runner().invoke(args=["make-admin", email])
        self.assertEqual(result.exit_code, 0, result.output)

    # Verify passwords are hashed and not exposed on the admin page
    def test_password_is_hashed_and_not_shown_to_admin(self):
        # Check that passwords are protected in storage and admin responses
        self.register("admin@example.com", "Admin")
        # Read the stored value to make sure the plain password isn't saved
        connection = self.app_module.open_database()
        password_hash = connection.execute(
            "SELECT password_hash FROM users WHERE email = ?",
            ("admin@example.com",),
        ).fetchone()["password_hash"]
        connection.close()
        self.assertNotEqual(password_hash, "correct-horse-battery")

        # Log in as an administrator so the account management page is available
        self.make_admin("admin@example.com")
        self.login("admin@example.com")
        page = self.client.get("/admin/users")
        self.assertEqual(page.status_code, 200)
        # Check that the plain password or a password label aren't exposed
        self.assertNotIn(b"correct-horse-battery", page.data)
        self.assertNotIn(b"Password:", page.data)

    # Verify that search input can't change the database query
    def test_search_does_not_interpret_sql(self):
        # Check that search input is treated as text instead of SQL
        self.register("member@example.com", "Member")
        self.register("admin@example.com", "Admin")
        # Use an administrator session to access the protected search page
        self.make_admin("admin@example.com")
        self.login("admin@example.com")

        # Submit text like SQL and confirm it doesn't return every account
        page = self.client.get("/admin/users?search=%27%20OR%201%3D1%20--")
        self.assertEqual(page.status_code, 200)
        self.assertIn(b"No users found.", page.data)
        self.assertNotIn(b"member@example.com", page.data)

    # Verify user content is escaped in HTML and inserted in the DOM safely
    def test_user_content_is_escaped_and_dom_output_is_safe(self):
        # Check that user content stays escaped in HTML and safe in the browser
        self.register("member@example.com", "Member")
        self.login("member@example.com")
        page = self.client.get("/profile")
        # Save markup as biography content to test the profile output
        self.client.post(
            "/profile",
            data={
                "csrf_token": self.csrf_token(page),
                "display_name": "Member",
                "biography": "<script>alert(1)</script>",
            },
        )
        page = self.client.get("/profile")
        # Jinja needs to display the markup as text instead of executing it
        self.assertIn(b"&lt;script&gt;alert(1)&lt;/script&gt;", page.data)
        self.assertNotIn(b"<script>alert(1)</script>", page.data)

        # Check the administrator search page with unsafe search and notice values
        self.register("admin@example.com", "Admin")
        self.make_admin("admin@example.com")
        self.login("admin@example.com")
        page = self.client.get(
            "/admin/users?search=%3Cscript%3Ealert(1)%3C%2Fscript%3E"
            "&notice=%3Cscript%3Ealert(1)%3C%2Fscript%3E"
        )
        self.assertEqual(page.status_code, 200)
        # The search value needs to remain escaped inside the form field
        self.assertIn(b"value=\"&lt;script&gt;alert(1)&lt;/script&gt;\"", page.data)
        self.assertNotIn(b'value="<script>alert(1)</script>"', page.data)
        self.assertIn(b"/static/js/admin.js", page.data)
        # The page can't insert the notice with unsafe HTML or source code
        self.assertNotIn(b"Search results for: <script>", page.data)
        self.assertNotIn(b".innerHTML = notice", page.data)
        # The separate script needs to insert the notice as text content
        script = self.client.get("/static/js/admin.js")
        self.assertIn(b".textContent = notice ||", script.data)

if __name__ == "__main__":
    unittest.main()
